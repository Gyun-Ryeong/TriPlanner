"""장소의 실내/실외 구분."""

# 일정/여행지 추천에 쓰는 '방문할 곳' 유형: 관광지·문화시설·축제·레포츠·쇼핑 (음식점 39, 숙박 32, 여행코스 25는 따로 다룸)
SIGHT_TYPES = {"12", "14", "15", "28", "38"}

# 콘텐츠 타입 중 대체로 실내인 것: 14=문화시설, 38=쇼핑, 39=음식점
INDOOR_TYPES = {"14", "38", "39"}

INDOOR_WORDS = (
    "박물관", "미술관", "전시", "아쿠아리움", "수족관", "과학관", "체험관", "도서관", "갤러리",
    "공연장", "극장", "영화", "스파", "찜질", "실내", "볼링", "키즈카페", "백화점", "아울렛", "쇼핑몰",
    "기념관", "홍보관", "카페",
)
# 한 글자 키워드("산", "섬", "숲")는 '부산'처럼 흔한 지명에 걸려 오판하므로 쓰지 않는다.
OUTDOOR_WORDS = (
    "해수욕장", "해변", "공원", "둘레길", "올레길", "갈맷길", "산책로", "등산로", "야외", "전망대", "등대", "폭포", "계곡",
    "오름", "정원", "수목원", "휴양림", "트레킹", "방파제", "낚시", "요트", "서핑", "캠핑", "해안", "해맞이", "일출", "일몰",
)


def is_indoor(place: dict) -> bool:
    """제목 키워드를 먼저 보고, 없으면 콘텐츠 타입으로 판단합니다. (완벽하지 않은 휴리스틱)"""
    title = place.get("title", "") or ""
    if "실내" in title:
        return True
    if any(w in title for w in OUTDOOR_WORDS):
        # '박물관'처럼 실내 단어도 함께 있으면 실내로 본다 (예: 해양박물관)
        return any(w in title for w in ("박물관", "미술관", "전시", "아쿠아리움", "과학관", "도서관", "기념관"))
    if any(w in title for w in INDOOR_WORDS):
        return True
    return str(place.get("content_type_id", "")) in INDOOR_TYPES
